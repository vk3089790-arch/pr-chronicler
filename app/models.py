"""Pydantic data models for PR Chronicler."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


# =====================================================================
# GitHub Webhook Models
# =====================================================================

class GitHubUser(BaseModel):
    """GitHub user information."""
    model_config = ConfigDict(extra="ignore")

    login: str = "unknown"
    id: Optional[int] = None
    avatar_url: Optional[str] = None


class GitHubRepo(BaseModel):
    """GitHub repository details."""
    model_config = ConfigDict(extra="ignore")

    id: Optional[int] = None
    name: str = ""
    full_name: str = ""
    owner: GitHubUser = Field(default_factory=GitHubUser)
    html_url: Optional[str] = None


class GitHubPullRequest(BaseModel):
    """GitHub pull request payload data."""
    model_config = ConfigDict(extra="ignore")

    id: Optional[int] = None
    number: int
    title: str = ""
    body: Optional[str] = None
    user: GitHubUser = Field(default_factory=GitHubUser)
    state: str = "closed"
    merged: bool = False
    merged_at: Optional[str] = None
    merge_commit_sha: Optional[str] = None
    html_url: str = ""


class GitHubWebhookPayload(BaseModel):
    """Top-level GitHub webhook payload for pull_request events."""
    model_config = ConfigDict(extra="ignore")

    action: str
    number: Optional[int] = None
    pull_request: Optional[GitHubPullRequest] = None
    repository: Optional[GitHubRepo] = None
    sender: Optional[GitHubUser] = None


