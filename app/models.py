# =====================================================================
# Structured Reflection Output Model
# =====================================================================

class ReflectionOutput(BaseModel):
    """Strict structured technical reflection generated by Gemini."""
    model_config = ConfigDict(extra="forbid")

    issue_details: str = Field(
        ...,
        description=(
            "Details of the issue or problem addressed, grounded strictly in PR/issue evidence. "
            "If the PR description or linked issues conflict with the actual diff, or if a claimed bug fix "
            "is not evidenced by the diff, explicitly note the discrepancy and distinguish [Verified] facts "
            "from [Unverified] claims."
        ),
    )
    execution_summary: str = Field(
        ...,
        description=(
            "Technical breakdown of the code changes, architecture, and files modified. "
            "Must be grounded primarily in the diff. Distinguish [Verified] diff facts from [Inferred] design intent. "
            "Do not make unsupported claims about performance or security unless verified in diff."
        ),
    )
    key_learnings: List[str] = Field(
        ...,
        description=(
            "Strictly between 3 and 4 concrete, evidence-grounded key engineering takeaways. "
            "Each takeaway must explain: (1) what changed, (2) why it matters, (3) the core engineering principle, "
            "and (4) supporting evidence with [Verified] or [Inferred] distinction. Avoid generic platitudes."
        ),
        min_length=3,
        max_length=4,
    )

    @field_validator("issue_details", "execution_summary")
    @classmethod
    def validate_non_empty_text(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field must contain non-empty text")
        return v.strip()

    @field_validator("key_learnings")
    @classmethod
    def validate_key_learnings(cls, v: List[str]) -> List[str]:
        if not (3 <= len(v) <= 4):
            raise ValueError(f"key_learnings must contain strictly between 3 and 4 items, got {len(v)}")
        cleaned = []
        for i, item in enumerate(v):
            if not isinstance(item, str) or not item.strip():
                raise ValueError(f"Key learning at index {i} must be a non-empty string")
            cleaned.append(item.strip())
        return cleaned


